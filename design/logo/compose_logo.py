"""Compose the final Bayesly logo: the owner's b (final_host geometry) as the first letter of
'ayesly' in Host Grotesk SemiBold (outlines exported from CoDesign at 400px, tracking -0.02).

Metrics read from the exported outlines (same text frame): baseline y=406, x-height top 207.56,
round overshoot top 202.78, l ascender top 117.66. Output goes to design/logo/final/.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / "final"
OUT.mkdir(exist_ok=True)
INK, LIME, PAPER = "#0D0D0E", "#C6FF2E", "#F5F5F0"

mark = json.loads(subprocess.check_output([sys.executable, str(HERE / "bmark.py")]))["final_host"]
MARK_D, MARK_TOP = mark["path"], mark["top"]          # units; ink x 100..500, y MARK_TOP..700

word_svg = (HERE / "host-ayesly-outline.svg").read_text(encoding="utf-8")
WORD_D = re.search(r'<path fill="[^"]+" d="([^"]+)"', word_svg).group(1)
nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", WORD_D)]
wx, wy = nums[0::2], nums[1::2]
W_L, W_R, W_T, W_B = min(wx), max(wx), min(wy), max(wy)

BASE, ROUND_TOP, XH_TOP, ASC_TOP = 406.0, 202.78, 207.56, 117.66
S = (BASE - ROUND_TOP) / 400.0            # px per mark unit: the bowl spans round-top..baseline
GAP = 0.07 * (BASE - XH_TOP)              # b-to-a ink gap at -0.02em tracking (measured)

# place the mark: unit y=700 -> baseline; unit x=500 (right ink) -> word's left ink - GAP
mx = (W_L - GAP) - 500 * S
my = BASE - 700 * S
mark_left, mark_top = mx + 100 * S, my + MARK_TOP * S

L, T = min(mark_left, W_L), min(mark_top, W_T)
R, B = W_R, W_B
PAD = 0
VB = f"{L - PAD:.2f} {T - PAD:.2f} {R - L + 2 * PAD:.2f} {B - T + 2 * PAD:.2f}"

def lockup(color):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VB}" width="{R - L:.0f}" height="{B - T:.0f}">'
            f'<g fill="{color}"><path transform="translate({mx:.3f} {my:.3f}) scale({S:.5f})" d="{MARK_D}"/>'
            f'<path d="{WORD_D}"/></g></svg>')

def bmark(color):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="100 {MARK_TOP} 400 {700 - MARK_TOP}" '
            f'width="400" height="{700 - MARK_TOP:.0f}"><path fill="{color}" d="{MARK_D}"/></svg>')

def avatar(bg, fg):
    # mark height ~60% of the square, optically centred (bowl mass sits low, so lift 2%)
    h = 600.0; s = h / (700 - MARK_TOP); w = 400 * s
    tx = (1000 - w) / 2 - 100 * s; ty = (1000 - h) / 2 - MARK_TOP * s - 20
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1000" height="1000">'
            f'<rect width="1000" height="1000" fill="{bg}"/>'
            f'<path fill="{fg}" transform="translate({tx:.2f} {ty:.2f}) scale({s:.5f})" d="{MARK_D}"/></svg>')

for name, col in (("ink", INK), ("paper", PAPER), ("lime", LIME)):
    (OUT / f"bayesly-logo-{name}.svg").write_text(lockup(col), encoding="utf-8")
    (OUT / f"bayesly-b-{name}.svg").write_text(bmark(col), encoding="utf-8")
(OUT / "bayesly-avatar-lime.svg").write_text(avatar(LIME, INK), encoding="utf-8")
(OUT / "bayesly-avatar-ink.svg").write_text(avatar(INK, LIME), encoding="utf-8")

# template asset: the lockup with currentColor, as a JS string the post templates inline
(HERE.parent / "logo.js").write_text(
    "/* Generated by design/logo/compose_logo.py: the Bayesly logo, inlined so it takes currentColor. */\n"
    "window.BAYESLY_LOGO = " + json.dumps(lockup("currentColor")) + ";\n", encoding="utf-8")
print(json.dumps({"viewBox": VB, "scale": S, "gap_px": GAP, "mark_top_px": mark_top, "l_top_px": ASC_TOP}))
